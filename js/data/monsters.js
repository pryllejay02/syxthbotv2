const path = require("path");

function monster({
  id,
  name,
  level,
  hp,
  attack,
  defense,
  dodge = 0,
  crit = 0,
  exp = 0,
  gold = 0,
  image,
}) {
  return {
    id,
    name,
    level: Number(level || 1),
    hp: Number(hp || 1),
    attack: Number(attack || 1),
    defense: Number(defense || 0),
    dodge: Number(dodge || 0),
    crit: Number(crit || 0),
    exp: Number(exp || 0),
    gold: Number(gold || 0),
    image: image
      ? path.join(__dirname, "../../img/monsters_img", image)
      : null,
  };
}

